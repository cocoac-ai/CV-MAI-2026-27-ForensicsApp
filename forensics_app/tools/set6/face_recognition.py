"""Set 6.3: Eigenfaces recognition with a simple, colorful Tkinter interface.

Uses the PCA model generated by Set 6.2. This tool opens its own window,
so the main app does not need an image loaded.
"""
import tkinter as tk
from tkinter import ttk, messagebox

import numpy as np
from PIL import Image, ImageDraw, ImageOps, ImageTk

from ..base import ForensicsTool
from .eigenface import PCA_FILE

MODEL_FILE = PCA_FILE  # saved by Set 6.2


def load_model():
    if not MODEL_FILE.exists():
        raise FileNotFoundError("PCA model not found. Run Set 6.2 — Eigenfaces (PCA) first.")
    with np.load(MODEL_FILE, allow_pickle=False) as model:
        keys = ("mean_face", "eigenfaces", "train_coefficients", "X_train",
                "X_test", "y_train", "y_test", "target_names", "image_shape")
        return {key: model[key] for key in keys}


def face_to_image(face, shape, size=(180, 220)):
    pixels = np.asarray(face).reshape(tuple(shape))
    # fetch_lfw_people produces floating-point images in the range 0..1.
    if pixels.max() <= 1.01:
        pixels = pixels * 255
    pixels = np.clip(pixels, 0, 255).astype(np.uint8)
    return ImageOps.fit(Image.fromarray(pixels).convert("RGB"), size)


def find_matches(model, test_index, k):
    """Project a held-out face into PCA space and rank training faces."""
    test_face = model["X_test"][test_index]
    # w = U_K^T (x - mean); eigenfaces are stored as rows.
    coefficients = (test_face - model["mean_face"]) @ model["eigenfaces"][:k].T
    distances = np.linalg.norm(model["train_coefficients"][:, :k] - coefficients, axis=1)
    matches = []
    for idx in np.argsort(distances):
        idx = int(idx)
        matches.append((idx, float(distances[idx])))
        if len(matches) == 3:
            break
    return matches


class RecognitionWindow:
    BG = "#f3f6fb"
    NAVY = "#17243a"
    MUTED = "#64748b"
    GREEN = "#167347"
    RED = "#b42332"

    def __init__(self, parent, model):
        self.model = model
        self.names = model["target_names"]
        self.window = tk.Toplevel(parent)
        self.window.title("Set 6 — Face Recognition")
        # Not bigger than the screen; the content scrolls if it does not fit.
        width = min(1200, self.window.winfo_screenwidth() - 80)
        height = min(950, self.window.winfo_screenheight() - 120)
        self.window.geometry(f"{width}x{height}")
        self.window.minsize(700, 500)
        self.window.configure(bg=self.BG)
        self.images = []  # Keep Tk PhotoImage references alive.
        self.body = self._make_scrollable()

        tk.Label(self.body, text="FACE RECOGNITION", font=("Helvetica", 23, "bold"),
                 bg=self.BG, fg=self.NAVY).pack(anchor="w", padx=30, pady=(24, 2))
        tk.Label(self.body, text="Eigenfaces (PCA)  •  3 nearest training faces",
                 font=("Helvetica", 12), bg=self.BG, fg=self.MUTED).pack(
                     anchor="w", padx=30, pady=(0, 20))

        controls = tk.Frame(self.body, bg="white", padx=18, pady=15)
        controls.pack(fill="x", padx=30)

        ids = np.unique(model["y_test"])
        self.people = sorted(((str(self.names[int(i)]), int(i)) for i in ids),
                             key=lambda pair: pair[0].lower())
        self.name_to_id = dict(self.people)
        self.person_var = tk.StringVar(value=self.people[0][0])
        self.photo_var = tk.StringVar()
        self.photo_indices = {}
        self.mode_var = tk.StringVar(value="name")
        self.number_var = tk.StringVar(value="0")
        self.k_var = tk.IntVar(value=min(50, len(model["eigenfaces"])))

        tk.Label(controls, text="CHOOSE TEST FACE BY", bg="white", fg=self.MUTED,
                 font=("Helvetica", 10, "bold")).grid(row=0, column=0, columnspan=4, sticky="w")
        tk.Radiobutton(controls, text="Person's name", variable=self.mode_var,
                       value="name", command=self.update_mode, bg="white").grid(
                           row=1, column=0, sticky="w", pady=(6, 8))
        tk.Radiobutton(controls, text="Test image number", variable=self.mode_var,
                       value="number", command=self.update_mode, bg="white").grid(
                           row=1, column=1, sticky="w", pady=(6, 8))

        tk.Label(controls, text="PERSON", bg="white", fg=self.MUTED,
                 font=("Helvetica", 10, "bold")).grid(row=2, column=0, sticky="w")
        tk.Label(controls, text="TEST PHOTO", bg="white", fg=self.MUTED,
                 font=("Helvetica", 10, "bold")).grid(row=2, column=1, sticky="w")
        tk.Label(controls, text=f"TEST INDEX (0–{len(model['X_test']) - 1})",
                 bg="white", fg=self.MUTED,
                 font=("Helvetica", 10, "bold")).grid(row=2, column=2, sticky="w")
        self.person_box = ttk.Combobox(controls, state="readonly", width=27,
                                       textvariable=self.person_var,
                                       values=[name for name, _ in self.people])
        self.person_box.grid(row=3, column=0, padx=(0, 12), pady=7, sticky="w")
        self.person_box.bind("<<ComboboxSelected>>", self.refresh_photos)
        self.photo_box = ttk.Combobox(controls, state="readonly", width=27,
                                      textvariable=self.photo_var)
        self.photo_box.grid(row=3, column=1, padx=(0, 12), pady=7, sticky="w")
        self.number_entry = ttk.Entry(controls, textvariable=self.number_var, width=15)
        self.number_entry.grid(row=3, column=2, padx=(0, 12), pady=7, sticky="w")

        tk.Label(controls, text="K — NUMBER OF EIGENFACES", bg="white", fg=self.MUTED,
                 font=("Helvetica", 10, "bold")).grid(
                     row=4, column=0, columnspan=2, sticky="w", pady=(12, 3))
        self.k_spin = tk.Spinbox(controls, from_=1, to=len(model["eigenfaces"]),
                                 textvariable=self.k_var, width=7,
                                 font=("Helvetica", 12))
        self.k_spin.grid(row=5, column=0, sticky="w")
        tk.Label(controls, text=f"Choose 1–{len(model['eigenfaces'])}. K changes the actual distances.",
                 bg="white", fg=self.MUTED, font=("Helvetica", 10)).grid(
                     row=5, column=1, columnspan=2, sticky="w")
        # ttk button: tk.Button colors are ignored on macOS (white text on gray).
        ttk.Button(controls, text="Recognize face",
                   command=self.recognize).grid(row=5, column=3, padx=12)

        self.status = tk.Label(self.body, text="Select a face to begin", bg="#e2e8f0",
                               fg=self.NAVY, font=("Helvetica", 15, "bold"),
                               anchor="w", padx=20, pady=13)
        self.status.pack(fill="x", padx=30, pady=(18, 12))

        self.cards = tk.Frame(self.body, bg=self.BG)
        self.cards.pack(fill="both", expand=True, padx=30)
        self.face_labels = []
        self.name_labels = []
        self.distance_labels = []
        for column in range(4):
            card = tk.Frame(self.cards, bg="white", padx=13, pady=14,
                            highlightbackground="#dce4ef", highlightthickness=1)
            card.grid(row=0, column=column, sticky="nsew", padx=5)
            self.cards.grid_columnconfigure(column, weight=1, uniform="cards")
            title = "TEST FACE" if column == 0 else f"MATCH {column}"
            tk.Label(card, text=title, font=("Helvetica", 12, "bold"),
                     bg="white", fg=self.NAVY).pack(anchor="w", pady=(0, 12))
            image_label = tk.Label(card, bg="#e2e8f0", width=180, height=220)
            image_label.pack()
            name_label = tk.Label(card, text="—", bg="white", fg=self.NAVY,
                                  font=("Helvetica", 12, "bold"), wraplength=200)
            name_label.pack(pady=(13, 5))
            distance_label = tk.Label(card, text="", bg="white", fg=self.MUTED,
                                      font=("Helvetica", 11))
            distance_label.pack()
            self.face_labels.append(image_label)
            self.name_labels.append(name_label)
            self.distance_labels.append(distance_label)

        # PCA coefficients are the numerical representation used for comparison.
        pca_panel = tk.Frame(self.body, bg="white", padx=18, pady=13,
                             highlightbackground="#dce4ef", highlightthickness=1)
        pca_panel.pack(fill="x", padx=35, pady=(14, 0))
        tk.Label(pca_panel, text="PCA COEFFICIENTS", bg="white", fg=self.NAVY,
                 font=("Helvetica", 13, "bold")).pack(anchor="w")
        self.pca_info = tk.Label(
            pca_panel, text="Select a face to view its PCA representation.",
            bg="white", fg=self.MUTED, font=("Helvetica", 11),
            anchor="w", justify="left", wraplength=1000)
        self.pca_info.pack(fill="x", pady=(6, 0))

        self.explanation = tk.Label(
            self.body, bg=self.BG, fg=self.MUTED, font=("Helvetica", 11),
            text="PCA distance: lower is better. The closest face is not always the correct identity.",
            anchor="w", justify="left")
        self.explanation.pack(fill="x", padx=30, pady=(14, 25))
        self.refresh_photos()
        self.update_mode()

    def _make_scrollable(self):
        """Put a frame inside a canvas with a scrollbar and return the frame."""
        canvas = tk.Canvas(self.window, bg=self.BG, highlightthickness=0)
        scrollbar = ttk.Scrollbar(self.window, orient="vertical", command=canvas.yview)
        canvas.configure(yscrollcommand=scrollbar.set)
        scrollbar.pack(side="right", fill="y")
        canvas.pack(side="left", fill="both", expand=True)
        body = tk.Frame(canvas, bg=self.BG)
        body_id = canvas.create_window((0, 0), window=body, anchor="nw")
        body.bind("<Configure>", lambda _e: canvas.configure(scrollregion=canvas.bbox("all")))
        canvas.bind("<Configure>", lambda e: canvas.itemconfigure(body_id, width=e.width))
        self.window.bind("<MouseWheel>", lambda e: canvas.yview_scroll(
            -1 if e.delta > 0 else 1, "units"))
        return body

    def update_mode(self):
        by_name = self.mode_var.get() == "name"
        self.person_box.configure(state="readonly" if by_name else "disabled")
        self.photo_box.configure(state="readonly" if by_name else "disabled")
        self.number_entry.configure(state="disabled" if by_name else "normal")

    def refresh_photos(self, *_):
        person_id = self.name_to_id[self.person_var.get()]
        indices = np.flatnonzero(self.model["y_test"] == person_id)
        self.photo_indices = {
            f"Photo {n} — index {int(index)}": int(index)
            for n, index in enumerate(indices, 1)
        }
        self.photo_box["values"] = list(self.photo_indices)
        self.photo_var.set(next(iter(self.photo_indices)))

    def recognize(self):
        try:
            k = int(self.k_var.get())
            if not 1 <= k <= len(self.model["eigenfaces"]):
                raise ValueError(f"K must be between 1 and {len(self.model['eigenfaces'])}.")
            if self.mode_var.get() == "name":
                index = self.photo_indices[self.photo_var.get()]
            else:
                index = int(self.number_var.get())
                if not 0 <= index < len(self.model["X_test"]):
                    raise ValueError(f"Test index must be 0–{len(self.model['X_test']) - 1}.")
                # Keep name and photo controls synchronized with the chosen index.
                actual_name = str(self.names[int(self.model["y_test"][index])])
                self.person_var.set(actual_name)
                self.refresh_photos()
                for caption, photo_index in self.photo_indices.items():
                    if photo_index == index:
                        self.photo_var.set(caption)
                        break
            matches = find_matches(self.model, index, k)
            actual = str(self.names[int(self.model["y_test"][index])])
            predicted = str(self.names[int(self.model["y_train"][matches[0][0]])])
            correct = predicted == actual
            self.status.configure(
                text=("✓  CORRECT RECOGNITION" if correct else "✕  INCORRECT RECOGNITION")
                + f"     Actual: {actual}   |   Predicted: {predicted}",
                bg=("#dcfce7" if correct else "#fee2e2"),
                fg=(self.GREEN if correct else self.RED))

            faces = [(self.model["X_test"][index], actual, None)]
            for train_index, distance in matches:
                faces.append((self.model["X_train"][train_index],
                              str(self.names[int(self.model["y_train"][train_index])]),
                              distance))
            self.images.clear()
            for column, (face, name, distance) in enumerate(faces):
                photo = ImageTk.PhotoImage(face_to_image(face, self.model["image_shape"]))
                self.images.append(photo)
                self.face_labels[column].configure(image=photo, width=180, height=220)
                self.name_labels[column].configure(text=name)
                self.distance_labels[column].configure(
                    text=(f"PCA distance: {distance:.2f}" if distance is not None
                          else f"Test image #{index}"))
            # w = U_K^T (x - mean): exactly the projection from the lecture.
            test_face = self.model["X_test"][index]
            coeff = (test_face - self.model["mean_face"]) @ self.model["eigenfaces"][:k].T
            preview = ",  ".join(f"{value:+.3f}" for value in coeff[:10])
            self.pca_info.configure(
                text=f"K = {k} eigenfaces  |  Test image #{index}\n"
                     f"First {min(10, len(coeff))} coefficients:  [{preview}]\n"
                     "Formula: w = U_Kᵀ (x − μ)  •  Euclidean distance compares these "
                     "coefficients with the first K saved training coefficients.")
            self.explanation.configure(
                text="PCA distance: LOWER is better. "
                     "Match 1 is the closest training face, not a guaranteed identity. "
                     "PCA coefficients are calculated from the saved Set 6.2 model using your chosen K.")
        except Exception as exc:
            messagebox.showerror("Face recognition error", str(exc), parent=self.window)


class FaceRecognitionTool(ForensicsTool):
    tool_id = "face_recognition"
    title = "Face Recognition (Eigenfaces)"
    category = "Set 6 · Faces"
    description = "Choose a person and test photo, then display three nearest PCA face matches."
    requires_image = False

    def run(self, parent: tk.Misc, document):
        try:
            model = load_model()
            RecognitionWindow(parent, model)
        except Exception as exc:
            messagebox.showerror("Face Recognition", str(exc), parent=parent)
        # Own window: don't ask main app to apply a result to an unloaded image.
        return None
